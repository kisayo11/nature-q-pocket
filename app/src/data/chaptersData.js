// 규정 코드로 챕터 번호 추출 (예: "1.1" -> 1, "2.1.3" -> 2, "10.4" -> 10)
export function getChapterIdByCode(code) {
  if (!code) return 1;
  const parts = code.split('.');
  const ch = parseInt(parts[0], 10);
  return isNaN(ch) ? 1 : ch;
}
